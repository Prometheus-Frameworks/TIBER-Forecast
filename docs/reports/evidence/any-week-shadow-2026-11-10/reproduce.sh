#!/usr/bin/env bash
# Reproduce the any-week shadow experiment from the retained inputs.
#
# Usage (from anywhere):
#   bash docs/reports/evidence/any-week-shadow-2026-11-10/reproduce.sh [WORKDIR]
#
# Writes only inside WORKDIR (default: a new temp dir). Needs python3 + requirements.txt. No network.
#
# Every required check below is fatal: a mismatch prints "FAIL: ..." on stderr, exits non-zero,
# stops all later stages and never reaches the final "OK" line. The only non-fatal comparison is
# the compressed-byte identity of the regenerated gzip (check 4c), which is reported, not required:
# gzip bytes depend on the Python/zlib build, the CSV inside does not.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORK="${1:-$(mktemp -d)}"

fail() {
  echo "FAIL: $*" >&2
  exit 1
}

# identical EXPECTED ACTUAL LABEL  -- exact byte comparison, fatal on any difference
identical() {
  [ -f "$1" ] || fail "$3: expected file is missing ($1)"
  [ -f "$2" ] || fail "$3: regenerated file is missing ($2)"
  if ! cmp -s "$1" "$2"; then
    fail "$3: regenerated bytes differ from the retained file"
  fi
  echo "   identical: $3"
}

# checksums DIR FILE LABEL  -- sha256sum -c inside DIR, fatal on any mismatch or missing file
checksums() {
  if ! (cd "$1" && sha256sum -c --quiet --strict "$2"); then
    fail "$3: SHA-256 check failed ($2)"
  fi
  echo "   verified:  $3"
}

run() {  # run LABEL STDOUT CMD...  -- fatal if the command exits non-zero
  local label="$1" out="$2"
  shift 2
  if ! "$@" > "$out"; then
    fail "$label: command exited non-zero"
  fi
}

mkdir -p "$WORK/raw" "$WORK/r1" "$WORK/r0" "$WORK/inspection" || fail "cannot create work dir $WORK"

echo "== 1. retained inputs"
checksums "$HERE/inputs" GZ.sha256 "retained gzip containers match GZ.sha256"
for f in "$HERE"/inputs/*.csv.gz; do
  gzip -dc "$f" > "$WORK/raw/$(basename "${f%.gz}")" || fail "cannot decompress $f"
done
checksums "$WORK/raw" "$HERE/inputs/RAW.sha256" "decompressed source bytes match RAW.sha256"

echo "== 2. as-run script (r1): re-run and compare with the preserved outputs"
run "r1 shadow.py" "$WORK/r1/stdout.txt" python3 -I "$HERE/original/as-run-r1/shadow.py" "$WORK/raw" "$WORK/r1"
identical "$HERE/original/as-run-r1/shadow_results.json" "$WORK/r1/shadow_results.json" "r1 shadow_results.json"
identical "$HERE/original/as-run-r1/shadow_week10_forecast.csv" "$WORK/r1/shadow_week10_forecast.csv" "r1 shadow_week10_forecast.csv"
run "r1 blocker.py" "$WORK/r1/blocker_stdout.txt" python3 -I "$HERE/original/as-run-r1/blocker.py" "$WORK/raw"
identical "$HERE/original/as-run-r1/blocker_stdout.txt" "$WORK/r1/blocker_stdout.txt" "r1 blocker_stdout.txt"

echo "== 3. reconstructed first revision (r0): re-run and compare with its retained regeneration"
run "r0 shadow_r0.py" "$WORK/r0/stdout.txt" python3 -I "$HERE/original/r0-reconstructed/shadow_r0.py" "$WORK/raw" "$WORK/r0"
identical "$HERE/original/r0-reconstructed/shadow_results.json" "$WORK/r0/shadow_results.json" "r0 shadow_results.json"
identical "$HERE/original/r0-reconstructed/shadow_week10_forecast.csv" "$WORK/r0/shadow_week10_forecast.csv" "r0 shadow_week10_forecast.csv"

echo "== 4. inspection addendum (same fit, asserted equal to r1)"
echo "-- 4a. retained artifact integrity"
checksums "$HERE/inspection" OUTPUTS.sha256 "all ten retained inspection files match OUTPUTS.sha256 (incl. the retained gzip)"
GZ_NAME=predictions_and_outcomes.csv.gz
gzip -t "$HERE/inspection/$GZ_NAME" || fail "retained $GZ_NAME is not a valid gzip stream"
gzip -dc "$HERE/inspection/$GZ_NAME" > "$WORK/inspection/retained_predictions_and_outcomes.csv" || fail "cannot decompress retained $GZ_NAME"
EXPECTED_CSV_SHA="$(awk '{print $1}' "$HERE/inspection/PREDICTIONS_CSV.sha256")"
ACTUAL_CSV_SHA="$(sha256sum "$WORK/inspection/retained_predictions_and_outcomes.csv" | awk '{print $1}')"
[ -n "$EXPECTED_CSV_SHA" ] || fail "PREDICTIONS_CSV.sha256 is empty"
if [ "$EXPECTED_CSV_SHA" != "$ACTUAL_CSV_SHA" ]; then
  fail "retained $GZ_NAME: decompressed CSV SHA-256 $ACTUAL_CSV_SHA does not match PREDICTIONS_CSV.sha256"
fi
echo "   verified:  decompressed CSV inside the retained gzip matches PREDICTIONS_CSV.sha256"

echo "-- 4b. reproduction of contents"
run "inspect_shadow.py" "$WORK/inspection/stdout.txt" python3 -I "$HERE/inspection/inspect_shadow.py" "$WORK/raw" "$HERE/original/as-run-r1" "$WORK/inspection"
for f in fit.json format_comparison_2024.json format_week_count_differences_2024.csv gate_assessment.json hodge.json metrics.json scoring.json week2_diagnostic.json week_summary.csv; do
  identical "$HERE/inspection/$f" "$WORK/inspection/$f" "inspection $f"
done
gzip -t "$WORK/inspection/$GZ_NAME" || fail "regenerated $GZ_NAME is not a valid gzip stream"
gzip -dc "$WORK/inspection/$GZ_NAME" > "$WORK/inspection/regenerated_predictions_and_outcomes.csv" || fail "cannot decompress regenerated $GZ_NAME"
identical "$WORK/inspection/retained_predictions_and_outcomes.csv" "$WORK/inspection/regenerated_predictions_and_outcomes.csv" "inspection predictions_and_outcomes.csv (decompressed contents, exact bytes, no normalisation)"

echo "-- 4c. compressed-byte identity (reported, not required)"
if cmp -s "$HERE/inspection/$GZ_NAME" "$WORK/inspection/$GZ_NAME"; then
  GZ_NOTE="regenerated gzip bytes also identical to the retained gzip"
else
  GZ_NOTE="regenerated gzip bytes DIFFER from the retained gzip (compression-only difference; CSV contents identical)"
fi
echo "   reported:  $GZ_NOTE"

echo "OK  all required checks passed; $GZ_NOTE. workdir: $WORK"
